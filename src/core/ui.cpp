int ums::Ui::appStuff(int argc_, char *argv_[])
{
    QApplication app(argc_, argv_);

    QQmlApplicationEngine engine;
    engine.loadFromModule("UmsContent", "App");

    if (engine.rootObjects().isEmpty())
    {
        return -1;
    }

    return app.exec();
}

