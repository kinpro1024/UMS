void ums::UmsDaemon::setGlobalState(ums::State new_state)
{
    state_ = new_state;
}

//--------------------------------------------------------------------------------------------------------------------------

ums::State ums::UmsDaemon::getGlobalState() const
{
    return state_;
}

//--------------------------------------------------------------------------------------------------------------------------

ums::Thermal& ums::UmsDaemon::getThermalRefFromManager()
{
    ums::Thermal& ref = subsystem_manager_->getThermalRef();
    return ref;
}